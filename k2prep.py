    w("=" * 66)
    w("")
    w("SCORE DISTRIBUTION")
    hist = defaultdict(int)
    for r in scored:
        hist[r.composite] += 1
    peak = max(hist.values()) if hist else 0
    for score in range(10, 0, -1):
        n = hist[score]
