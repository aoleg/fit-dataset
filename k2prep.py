    already = [r for r in results if r.status == ST_ALREADY]
    below = [r for r in results if r.status == ST_BELOW]
    small = [r for r in results if r.status == ST_SMALL]
    errors = [r for r in results if r.status == ST_ERROR]
    tiered = [r for r in results if r.tier is not None and r.status != ST_ERROR]

    name_w = max([26] + [len(r.name) for r in results]) + 2

    fmt_desc = "png-compress6" if args.png else "jpeg-q97-444"
