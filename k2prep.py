EPS = 1e-6


# ---------------------------------------------------------------------------
# 4.1  Tiers
# ---------------------------------------------------------------------------

TIERS = [1024, 768, 512]          # nominal resolution, descending
UPSCALE_TOLERANCE = 1.15          # max permitted linear upscale into a tier

# 256 is deliberately not a tier. Anything that does not reach 512 is skipped.
# 768 exists for demotion granularity: without it the gap between tiers is 4x
# in area and near-boundary images lose most of their pixels.

BATCH_SIZE_BY_TIER = {1024: 2, 768: 3, 512: 8}


# ---------------------------------------------------------------------------
# 4.2  Bucket generation - must match musubi-tuner exactly
# ---------------------------------------------------------------------------

RESO_STEPS = 16                   # VAE f8 compression x patch size 2


def divisible_by(n: int, d: int) -> int:
    return n - n % d


@lru_cache(maxsize=None)
def generate_buckets(resolution: int, steps: int = RESO_STEPS) -> list[tuple[int, int]]:
    """Byte-for-byte equivalent to musubi-tuner's bucket list for a square target.

    Port of ``BucketSelector.__init__`` from ``src/musubi_tuner/dataset/bucket.py``.
    Do not "simplify" this to rounding sqrt(area * AR) to a multiple of 16; the
    two methods disagree (4:3 at 1024 is 1184x880 here, 1168x880 by rounding).
    """
    area = resolution * resolution
    sqrt_size = int(math.sqrt(area))
    min_size = divisible_by(sqrt_size // 2, steps)
    out: list[tuple[int, int]] = []
    for w in range(min_size, sqrt_size + steps, steps):
        h = divisible_by(area // w, steps)
        out.append((w, h))
        out.append((h, w))
    return sorted(set(out))


# ---------------------------------------------------------------------------
# 4.3  Aspect-ratio families
# ---------------------------------------------------------------------------

AR_FAMILIES = ["9:16", "2:3", "4:5", "1:1", "5:4", "3:2", "16:9"]
# The actual 1024-tier bucket ratios, not the idealised ones:
# 9:16 is 0.5647 not 0.5625, 4:5 is 0.8028 not 0.8000.
AR_NOMINAL = [0.5647, 0.6667, 0.8028, 1.0000, 1.2456, 1.5000, 1.7708]


@lru_cache(maxsize=None)
def bucket_for(tier: int, family: str) -> tuple[int, int]:
    """Resolve a family to its bucket at ``tier``.

    The per-tier dimensions differ, because the 16px grid is coarser relative to
    a smaller image. This is why the crop box cannot be computed until the tier
    is known.
    """
    nominal = AR_NOMINAL[AR_FAMILIES.index(family)]
    return min(generate_buckets(tier), key=lambda b: abs(b[0] / b[1] - nominal))


def assign_family(src_ar: float) -> str:
    """Nearest family by ratio. No guard, no exclusion - a 21:9 panorama is
    assigned to 16:9 and cropped hard, on purpose."""
    idx = min(range(len(AR_NOMINAL)), key=lambda i: abs(AR_NOMINAL[i] - src_ar))
    return AR_FAMILIES[idx]


# ---------------------------------------------------------------------------
# 6  Quality scoring bands - fixed absolute scales, never percentiles
# ---------------------------------------------------------------------------

# 6.1  Q - estimated JPEG quality -> score. (min_quality, score), descending.
Q_BANDS = [(98, 10), (95, 9), (92, 8), (88, 7), (84, 6),
           (78, 5), (72, 4), (65, 3), (55, 2)]

# 6.2  B - blockiness ratio -> score. (max_ratio, score), ascending.
B_BANDS = [(1.05, 10), (1.10, 9), (1.15, 8), (1.20, 7), (1.30, 6),
           (1.40, 5), (1.55, 4), (1.75, 3), (2.00, 2)]

# 6.3  D - detail ratio -> score. (min_ratio, score), descending.
#
# THESE BANDS ARE A STARTING POINT AND ARE EXPLICITLY UNCALIBRATED. They produce
# genuine false positives on bokeh, fog, snow, and deliberately minimal
# compositions. Run --report on a real folder, look at the QUALITY DISTRIBUTION
# histogram, and adjust these numbers before trusting --threshold to act on D.
D_BANDS = [(0.070, 10), (0.055, 9), (0.045, 8), (0.035, 7), (0.026, 6),
           (0.019, 5), (0.013, 4), (0.008, 3), (0.004, 2)]

# Standard IJG luma quantization table, natural (row-major) order, which is what
# Pillow's Image.quantization returns.
STD_LUMA_QT = [
    16, 11, 10, 16, 24, 40, 51, 61,
    12, 12, 14, 19, 26, 58, 60, 55,
    14, 13, 16, 24, 40, 57, 69, 56,
    14, 17, 22, 29, 51, 87, 80, 62,
    18, 22, 37, 56, 68, 109, 103, 77,
    24, 35, 55, 64, 81, 104, 113, 92,
    49, 64, 78, 87, 103, 121, 120, 101,
    72, 92, 95, 98, 112, 100, 103, 99,
]

# Normalised sum-of-squares residual above which the encoder is judged to have
# used non-standard tables (common with Adobe and several phone encoders). An
# exact IJG-scaled table fits at 0.0; Google's and Adobe's custom tables land
# well above this.
QT_RESIDUAL_MAX = 0.02

# B and D are computed on at most this square of centre pixels, for speed.
METRIC_CROP = 1024


