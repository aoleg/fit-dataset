def _threshold_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threshold must be an integer, got {value!r}")
    if not 0 <= n <= 10:
        raise argparse.ArgumentTypeError(f"--threshold must be 0..10, got {n}")
    return n


def _threads_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threads must be an integer, got {value!r}")
    if not 1 <= n <= 32:
        raise argparse.ArgumentTypeError(f"--threads must be 1..32, got {n}")
    return n


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        prog="k2prep",
        description="Crop and resize a folder of photographs onto musubi-tuner's "
                    "exact bucket dimensions for Krea 2 LoRA training.",
    )
    p.add_argument("folder", help="Input folder. Non-recursive. Never modified.")
    p.add_argument("--report", action="store_true",
                   help="Dry run: analyse and write a report, write no images.")
    p.add_argument("--threshold", type=_threshold_arg, default=0, metavar="N",
                   help="Process only images whose composite score >= N (0..10). "
                        "Default 0.")
    p.add_argument("--png", action="store_true",
                   help="Write PNG instead of JPEG q97 4:4:4.")
    p.add_argument("--filter", choices=sorted(RESAMPLE_FILTERS), default="lanczos",
                   help="Resampling filter. Default lanczos.")
    p.add_argument("--threads", type=_threads_arg, default=4, metavar="N",
                   help="Worker threads, 1..32. Default 4.")
    p.add_argument("--force", action="store_true",
                   help="Overwrite existing outputs instead of skipping.")
    p.add_argument("--sort", action="store_true",
                   help=f"Triage instead of building a dataset: score every "
                        f"image at the {SORT_TIER} tier and copy the ORIGINAL, "
                        f"with its .txt sidecar, into _prep/"
                        f"{SORT_DIR_PREFIX}1 .. _prep/{SORT_DIR_PREFIX}10 by "
                        f"score. Writes no tier folders and no TOML.")
    p.add_argument("--move", action="store_true",
                   help="With --sort, move the originals instead of copying "
                        "them. This is the only k2prep option that removes "
                        "anything from the source folder.")
    p.add_argument("--single-pass", action="store_true", dest="single_pass",
                   help="Score the source image and reject before rendering, "
                        "instead of scoring the rendered result. Faster, but "
                        "quality is resolution-dependent: a large source that "
                        "cleans up beautifully at 1024 is judged on pixels the "
                        "trainer never sees.")
    p.add_argument("--no-merge", action="store_true", dest="no_merge",
                   help=f"Do not consolidate buckets holding fewer than "
                        f"{MIN_BUCKET_SIZE} images. Every image stays in the "
                        f"bucket its own aspect ratio picks, undersized buckets "
                        f"and all.")
    p.add_argument("--version", action="version", version=f"k2prep {__version__}")
    args = p.parse_args(argv)
    if args.move and not args.sort:
        p.error("--move is only available with --sort; on its own it would have "
                "nothing to move and would still delete your originals")
    return args


