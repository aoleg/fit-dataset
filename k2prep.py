def _fmt_int(n: int) -> str:
    return f"{n:,}"


def _hms(seconds: float) -> str:
    m, s = divmod(int(round(seconds)), 60)
    h, m = divmod(m, 60)
    if h:
        return f"{h}h {m}m {s}s"
    if m:
        return f"{m}m {s}s"
    return f"{s}s"


def _failed_metrics(res: Result) -> str:
    parts = []
    if res.q is not None and res.q == res.composite:
        est = f"est. q{res.q_est}" if res.q_est is not None else "lossless"
        parts.append(f"Q={res.q} ({est})")
    if res.b is not None and res.b == res.composite:
        flag = "?" if res.b_unreliable else ""
        parts.append(f"B={res.b}{flag} (ratio {res.b_ratio:.2f})")
    if res.d is not None and res.d == res.composite:
        parts.append(f"D={res.d} (ratio {res.d_ratio:.3f})")
    return ", ".join(parts)


def _score_cell(score: int | None, flag: bool = False) -> str:
    if score is None:
        return "n/a"
    return f"{score}{'?' if flag else ''}"


