#!/usr/bin/env python3
"""k2prep - dataset preprocessor for musubi-tuner / Krea 2 LoRA training.

Takes a messy folder of mixed photographs and produces a small, clean,
bucket-tight training set: every accepted image is cropped and resized to land
on exactly one of 7 aspect-ratio families across 3 resolution tiers, using
dimensions generated by musubi-tuner's own bucket algorithm so the trainer
never re-crops.

Rejected images are skipped entirely. The source folder is never written to,
moved within, or deleted from. The report is the only record of a rejection.

Single file by design; see SPEC.md section 2.
"""

