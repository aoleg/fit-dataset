# ---------------------------------------------------------------------------
# 5.4  Crop geometry
# ---------------------------------------------------------------------------

def crop_dims(w: int, h: int, target_ar: float) -> tuple[int, int]:
    """Minimal crop to the target ratio, in source pixels."""
    if w / h > target_ar:
        cw, ch = int(round(h * target_ar)), h        # too wide: trim width
    else:
        cw, ch = w, int(round(w / target_ar))        # too tall: trim height
    return max(1, min(cw, w)), max(1, min(ch, h))


def crop_box(src_w: int, src_h: int, target_ar: float) -> tuple[int, int, int, int]:
    """(src_w, src_h, target_ar) -> (left, top, right, bottom).

    THE --anchor SEAM. Every crop box in this program is computed here and
    nowhere else; a face-aware anchor is a drop-in replacement with the same
    signature.

    Horizontal is always centred. Vertical is centred except for portrait
    targets, where the origin is biased to 1/3 of the excess: heads sit above
    centre in almost all photography and this is right more often than centre
    at zero cost.
    """
    cw, ch = crop_dims(src_w, src_h, target_ar)
    left = (src_w - cw) // 2
    top = int((src_h - ch) * (1 / 3 if target_ar < 1.0 else 1 / 2))
    return (left, top, left + cw, top + ch)


def needed_area(tier: int, family: str) -> int:
    """Minimum post-crop source area to qualify for a tier without exceeding
    UPSCALE_TOLERANCE."""
    bw, bh = bucket_for(tier, family)
    return int((bw * bh) / (UPSCALE_TOLERANCE ** 2))


def assign_tier(src_w: int, src_h: int, family: str):
    """First tier (descending) whose bucket the post-crop source can fill.

    The area test uses post-crop dimensions. A 2400x600 panorama has 1.44 MP but
    only 1067x600 = 0.64 MP after cropping to the 768-tier 16:9 ratio, so it
    belongs in 768. Testing raw source area would place it in 1024 and force an
    upscale.
    """
    for tier in TIERS:
        bw, bh = bucket_for(tier, family)
        cw, ch = crop_dims(src_w, src_h, bw / bh)
        if cw * ch >= (bw * bh) / (UPSCALE_TOLERANCE ** 2):
            return tier, (bw, bh), (cw, ch)
    return None


# ---------------------------------------------------------------------------
# 6.1  Q - compression quality
# ---------------------------------------------------------------------------

@lru_cache(maxsize=None)
def _ijg_scaled_table(q: int) -> tuple[int, ...]:
    scale = 5000 // q if q < 50 else 200 - 2 * q
    return tuple(min(255, max(1, (v * scale + 50) // 100)) for v in STD_LUMA_QT)


def estimate_jpeg_quality(table) -> int | None:
    """Best-fit IJG quality for a luma quantization table, or None if the
    encoder used non-standard tables."""
    t = list(table)
    if len(t) != 64:
        return None
    best_q, best_ssd = 100, None
    for q in range(1, 101):
        std = _ijg_scaled_table(q)
        ssd = 0
        for a, b in zip(std, t):
            d = a - b
            ssd += d * d
        if best_ssd is None or ssd < best_ssd:
            best_q, best_ssd = q, ssd
    energy = sum(v * v for v in t)
    if energy <= 0:
        return None
    if best_ssd / energy > QT_RESIDUAL_MAX:
        return None
    return best_q


def score_q(q_est: int | None) -> int | None:
    if q_est is None:
        return None
    for lo, s in Q_BANDS:
        if q_est >= lo:
            return s
    return 1


# ---------------------------------------------------------------------------
# 6.2  B - blockiness
# ---------------------------------------------------------------------------

def _axis_block_ratio(arr: np.ndarray) -> float:
    """Ratio of mean absolute difference across 8-aligned column boundaries to
    all other column boundaries."""
    if arr.shape[1] < 10:
        return 1.0
    diff = np.abs(arr[:, 1:] - arr[:, :-1]).mean(axis=0)
    x = np.arange(1, arr.shape[1])
    aligned = diff[x % 8 == 0]
    other = diff[x % 8 != 0]
    if aligned.size == 0 or other.size == 0:
        return 1.0
    return float(aligned.mean() / max(float(other.mean()), EPS))


def blockiness_ratio(arr: np.ndarray) -> float:
    return max(_axis_block_ratio(arr), _axis_block_ratio(arr.T))


def score_b(ratio: float) -> int:
    for hi, s in B_BANDS:
        if ratio <= hi:
            return s
    return 1


# ---------------------------------------------------------------------------
# 6.3  D - detail
# ---------------------------------------------------------------------------

def detail_ratio(luma: Image.Image) -> float:
    w, h = luma.size
    if w < 4 or h < 4:
        return 0.0
    small = luma.resize((max(1, w // 2), max(1, h // 2)), Image.BOX)
    back = small.resize((w, h), Image.BILINEAR)
    a = np.asarray(luma, dtype=np.float32)
    b = np.asarray(back, dtype=np.float32)
    hf = float(np.abs(a - b).mean())
    # Normalising by contrast keeps low-contrast but sharp images from being
    # penalised.
    return float(hf / max(float(a.std()), EPS))


def score_d(ratio: float) -> int:
    for lo, s in D_BANDS:
        if ratio >= lo:
            return s
    return 1


# ---------------------------------------------------------------------------
# 5.1  Load and normalise
# ---------------------------------------------------------------------------

def _to_rgb(img: Image.Image) -> Image.Image:
    """Convert to RGB. RGBA/LA/transparent-P are composited over white rather
    than having the alpha channel dropped."""
    mode = img.mode
    if mode == "RGB":
        return img
    if mode in ("RGBA", "LA") or (mode == "P" and "transparency" in img.info):
        rgba = img.convert("RGBA")
        bg = Image.new("RGB", rgba.size, (255, 255, 255))
        bg.paste(rgba, mask=rgba.split()[-1])
        return bg
    if mode == "I" or mode.startswith("I;16"):
        a = np.asarray(img).astype(np.float32) / 256.0
        return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "L").convert("RGB")
    if mode == "F":
        a = np.asarray(img, dtype=np.float32)
        lo, hi = float(a.min()), float(a.max())
        a = (a - lo) / max(hi - lo, EPS) * 255.0
        return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "L").convert("RGB")
    return img.convert("RGB")


def load_source(path: Path) -> tuple[Image.Image, str, dict | None]:
    """Open, reject animated input, EXIF-transpose, convert to RGB.

    exif_transpose must happen before dimensions are read: phone and DSLR
    portraits are stored landscape with an orientation tag, and skipping this
    bucket-assigns them along the wrong axis.
    """
    img = Image.open(path)
    fmt = img.format or ""
    qtables = getattr(img, "quantization", None)
    n_frames = getattr(img, "n_frames", 1)
    if n_frames and n_frames > 1:
        raise ValueError(
            f"animated {fmt or 'image'} rejected ({n_frames} frames); "
            "k2prep processes still images only"
        )
    img = ImageOps.exif_transpose(img)
    img = _to_rgb(img)
    return img, fmt, qtables


def _metric_crop(luma: Image.Image) -> Image.Image:
    """Centre crop to at most METRIC_CROP square, snapped to the 8px grid so the
    blockiness metric still sees the DCT block boundaries."""
    w, h = luma.size
    if w <= METRIC_CROP and h <= METRIC_CROP:
        return luma
    cw, ch = min(w, METRIC_CROP), min(h, METRIC_CROP)
    left = ((w - cw) // 2) // 8 * 8
    top = ((h - ch) // 2) // 8 * 8
    return luma.crop((left, top, left + cw, top + ch))


