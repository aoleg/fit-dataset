TOML_HEADER = """\
{marker} on {stamp}
#
# Do not set bucket_no_upscale = true. It bypasses the bucket list entirely and
# assigns each image its own dimensions floored to 16, which is exactly the
# bucket explosion this tool exists to prevent.
#
# batch_size values below keep the per-step latent token count roughly constant
# across tiers (~4,080 tokens at 1024, ~2,300 at 768, ~1,010 at 512). Lower them
# if VRAM says otherwise.
#
# num_repeats is 1 everywhere. Per-tier and per-concept balancing is your job;
# an unbalanced dataset combined with a high learning rate is the worst case for
# multi-concept training.

[general]
caption_extension = ".txt"
"""


def emit_toml(prep_dir: Path, stamp: datetime) -> Path | None:
    blocks = []
    for tier in TIERS:
        tier_dir = prep_dir / str(tier)
        if not tier_dir.is_dir():
            continue
        if not any(p.suffix.lower() in KNOWN_EXTENSIONS or p.suffix in KNOWN_EXTENSIONS
                   for p in tier_dir.iterdir() if p.is_file()):
            continue
        # Forward slashes: TOML and Windows backslashes interact badly.
        directory = str(tier_dir.resolve()).replace("\\", "/")
        blocks.append(
            "\n[[datasets]]\n"
            f'image_directory = "{directory}"\n'
            f"resolution = [{tier}, {tier}]\n"
            "enable_bucket = true\n"
            "bucket_no_upscale = false\n"
            f"batch_size = {BATCH_SIZE_BY_TIER[tier]}\n"
            "num_repeats = 1\n"
        )
    if not blocks:
        return None

    # The TOML is a generated artifact and every run rewrites it, so k2prep's own
    # output is replaced in place rather than accumulating dataset-2, -3, -4.
    # A file it did not write is never overwritten.
    dest = prep_dir / TOML_FILENAME
    if dest.exists():
        try:
            ours = dest.read_text(encoding="utf-8").startswith(TOML_MARKER)
        except OSError:
            ours = False
        n = 1
        while not ours and dest.exists():
            n += 1
            dest = prep_dir / f"dataset-{n}.toml"
            ours = (not dest.exists() or
                    dest.read_text(encoding="utf-8").startswith(TOML_MARKER))
    dest.write_text(
        TOML_HEADER.format(marker=TOML_MARKER, stamp=f"{stamp:%Y-%m-%d %H:%M:%S}")
        + "".join(blocks),
        encoding="utf-8",
    )
    return dest


