# Per-image result
# ---------------------------------------------------------------------------

# status values
ST_CANDIDATE = "candidate"   # fits a tier; threshold not yet applied
ST_ACCEPTED = "accepted"     # will be / was written
ST_ALREADY = "already"       # output already present, not --force
ST_BELOW = "below"           # composite < threshold
ST_SMALL = "small"           # fits no tier
ST_ERROR = "error"


@dataclass
class Result:
    path: Path
    name: str
    status: str = ST_CANDIDATE
    error: str = ""

    src_w: int = 0
    src_h: int = 0
    src_ar: float = 0.0

    family: str | None = None
    tier: int | None = None
    bucket: tuple[int, int] | None = None
    crop: tuple[int, int] | None = None
    box: tuple[int, int, int, int] | None = None
    crop_pct: float = 0.0
    r_factor: float = 0.0
    need: int = 0

    q: int | None = None
    q_est: int | None = None
    b: int | None = None
    b_ratio: float = 0.0
    b_unreliable: bool = False
    d: int | None = None
    d_ratio: float = 0.0
    composite: int = 10
    no_metrics: bool = False

    out_stem: str = ""
    out_name: str = ""
    caption_src: Path | None = None
    caption_borrowed: bool = False
    collided: bool = False


def analyse(path: Path) -> Result:
    """Phase A: everything that can be decided without writing anything."""
    res = Result(path=path, name=path.name)
    try:
        img, fmt, qtables = load_source(path)

        res.src_w, res.src_h = img.size
        if res.src_w < 1 or res.src_h < 1:
            raise ValueError("zero-sized image")
        res.src_ar = res.src_w / res.src_h

        # 5.2 family, 5.3 tier
        res.family = assign_family(res.src_ar)
        fit = assign_tier(res.src_w, res.src_h, res.family)
        if fit is None:
            bw, bh = bucket_for(TIERS[-1], res.family)
            res.crop = crop_dims(res.src_w, res.src_h, bw / bh)
            res.need = needed_area(TIERS[-1], res.family)
            res.status = ST_SMALL
            return res

        res.tier, res.bucket, res.crop = fit
        res.need = needed_area(res.tier, res.family)
        bw, bh = res.bucket
        res.box = crop_box(res.src_w, res.src_h, bw / bh)
        cw, ch = res.crop
        res.crop_pct = (1.0 - (cw * ch) / (res.src_w * res.src_h)) * 100.0
        res.r_factor = math.sqrt((cw * ch) / (bw * bh))

        # 6  metrics, on the source after transpose and RGB conversion
        if fmt in ("PNG", "BMP"):
            res.q_est, res.q = None, 10          # lossless input
        elif qtables:
            res.q_est = estimate_jpeg_quality(qtables[min(qtables)])
            res.q = score_q(res.q_est)
        else:
            res.q_est, res.q = None, None        # unknown encoder, excluded

        luma = _metric_crop(img.convert("L"))
        arr = np.asarray(luma, dtype=np.float32)
        res.b_ratio = blockiness_ratio(arr)
        res.b = score_b(res.b_ratio)
        # The 8px grid no longer aligns if the image was rescaled after being
        # JPEG-encoded, so B reads clean on genuinely damaged material.
        res.b_unreliable = res.q is None and not (res.src_w % 8 == 0 and res.src_h % 8 == 0)
        res.d_ratio = detail_ratio(luma)
        res.d = score_d(res.d_ratio)

        scores = [s for s in (res.q, res.b, res.d) if s is not None]
        if scores:
            res.composite = min(scores)          # minimum, not weighted mean
        else:
            res.composite = 10
            res.no_metrics = True

        img.close()
    except Exception as exc:  # one image raising must not kill the run
        res.status = ST_ERROR
        res.error = f"{type(exc).__name__}: {exc}"
    return res


# ---------------------------------------------------------------------------
# 5.5 - 5.7  Write
# ---------------------------------------------------------------------------

def write_output(res: Result, out_dir: Path, resample: int, as_png: bool) -> None:
    img, _fmt, _qt = load_source(res.path)
    try:
        # Crop and resize in one pass; the filter operates directly on the crop
        # region. No intermediate image, no extra rounding.
        out = img.resize(res.bucket, resample=resample, box=res.box)
    finally:
        img.close()
    dest = out_dir / res.out_name
    # No exif=, no icc_profile=: EXIF is not carried to the output, which is
    # what prevents orientation being applied twice by downstream viewers.
    if as_png:
        out.save(dest, "PNG", compress_level=6)
    else:
        out.save(dest, "JPEG", quality=97, subsampling=0, optimize=True)
    out.close()
    if res.caption_src is not None:
        shutil.copyfile(res.caption_src, out_dir / f"{res.out_stem}.txt")


# ---------------------------------------------------------------------------
# 7.1  Scanning
# ---------------------------------------------------------------------------

def scan_folder(folder: Path) -> tuple[list[Path], list[str]]:
    """Non-recursive. Returns (image paths sorted by filename, unknown-extension
    filenames sorted). --recursive is a Phase 2 hook: this stays one function
    returning a list of paths."""
    images: list[Path] = []
    unknown: list[str] = []
    for entry in os.scandir(folder):
        if entry.is_dir():
            continue                              # includes _prep/
        name = entry.name
        ext = os.path.splitext(name)[1]
        if ext in KNOWN_EXTENSIONS:
            images.append(Path(entry.path))
        elif ext.lower() != ".txt":
            unknown.append(name)
    images.sort(key=lambda p: p.name)
    unknown.sort()
    return images, unknown


def caption_for(path: Path) -> Path | None:
    cap = path.parent / f"{path.stem}.txt"
    return cap if cap.is_file() else None


# ---------------------------------------------------------------------------
# 7.2  Filename collisions - sequential, main thread, scan order
# ---------------------------------------------------------------------------

def resolve_names(accepted: list[Result], ext: str) -> list[str]:
    """Assign output stems, resolve collisions per tier folder, and share a lone
    caption across colliding stems. Returns report lines."""
    taken: dict[int, set[str]] = defaultdict(set)
    groups: dict[tuple[int, str], list[Result]] = defaultdict(list)
    lines: list[str] = []

    for res in accepted:                          # scan order
        stem = res.path.stem
        candidate, n = stem, 1
        while candidate in taken[res.tier]:
            n += 1
            candidate = f"{stem}_{n}"
        taken[res.tier].add(candidate)
        res.out_stem = candidate
        res.out_name = candidate + ext
        res.collided = candidate != stem
        groups[(res.tier, stem)].append(res)

    for (_tier, stem), group in groups.items():
        if len(group) < 2:
            continue
        # Colliding stems are almost always the same photograph in two formats,
        # so a lone caption applies to all of them.
        with_caption = [r for r in group if r.caption_src is not None]
        if len(with_caption) == 1:
            src = with_caption[0].caption_src
            for r in group:
                if r.caption_src is None:
                    r.caption_src = src
                    r.caption_borrowed = True
        for r in group:
            if not r.collided:
                continue
            note = ""
            if r.caption_src is not None:
                note = f"   (caption copied from {r.caption_src.name})"
            lines.append(f"{r.name} -> {r.out_name}{note}")

    lines.sort()
    return lines


