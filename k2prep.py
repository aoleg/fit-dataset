# --sort run
# ---------------------------------------------------------------------------

def run_sort(args, folder: Path, prep_dir: Path, reports_dir: Path,
             images: list[Path], unknown: list[str], resample: int,
             started: datetime, t0: float) -> int:
    """Triage a folder by quality. Builds no dataset: no tier folders, no TOML.

    Kept separate from the dataset pipeline on purpose. Under --move the source
    images leave the folder, which would pull the rug from under a tier build
    running in the same pass - the next run would find no sources and sweep the
    tier folders empty.
    """
    notes: list[str] = []
    for flag, why in (("threshold", "nothing is rejected when sorting; every "
                                    "image goes to the folder for its score"),
                      ("png", "originals are placed verbatim, so the output "
                              "format option does not apply"),
                      ("single_pass", f"sorting always scores the rendered "
                                      f"{SORT_TIER}-tier image, which is what "
                                      f"the score means"),
                      ("no_merge", "sorting does not use buckets")):
        value = getattr(args, flag, None)
        if value:
            notes.append(f"--{flag.replace('_', '-')} ignored: {why}.")

    results: list[Result] = []
    if images:
        with ThreadPoolExecutor(max_workers=args.threads) as pool:
            futures = [pool.submit(analyse_for_sort, p) for p in images]
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="scanning ", unit="img"):
                results.append(fut.result())
    results.sort(key=lambda r: r.name)
    for r in results:
        if r.status == ST_CANDIDATE:
            r.caption_src = caption_for(r.path)

    # -- score, at the 1024 tier, with the same cache the dataset run uses ----
    todo = [r for r in results if r.status == ST_CANDIDATE]
    cache_hits = 0
    if todo:
        cache = {} if args.force else load_score_cache(prep_dir)
        pending = []
        for r in todo:
            if apply_cached_score(r, cache):
                cache_hits += 1
            else:
                pending.append(r)
        if pending:
            with ThreadPoolExecutor(max_workers=args.threads) as pool:
                futures = {pool.submit(score_rendered, r, resample): r
                           for r in pending}
                for fut in tqdm(as_completed(futures), total=len(futures),
                                desc="scoring  ", unit="img"):
                    r = futures[fut]
                    try:
                        fut.result()
                    except Exception as exc:
                        r.status = ST_ERROR
                        r.error = f"{type(exc).__name__}: {exc}"

    # -- place, sequentially: moving files is not worth parallelising ---------
    for r in results:
        if r.scored and r.status != ST_ERROR:
            place_sorted(r, prep_dir, args.move, args.force, args.report)
    stale = find_stale_sorted(prep_dir, results)

    elapsed = time.perf_counter() - t0
    finished = datetime.now()

    if todo:
        save_score_cache(prep_dir, results, finished)
        notes.append(f"scores cached in {CACHE_FILENAME} "
                     f"({cache_hits} of {len(todo)} reused this run).")
    for note in notes:
        print(f"note: {note}")

    reports_dir.mkdir(parents=True, exist_ok=True)
    report_path = _free_path(reports_dir, f"sort-{started:%Y%m%d-%H%M%S}", ".txt")
    report_path.write_text(
        build_sort_report(args, folder, results, unknown, stale,
                          started, finished, elapsed, notes),
        encoding="utf-8",
    )

    counts = defaultdict(int)
    for r in results:
        counts[r.sort_action] += 1
    errors = sum(1 for r in results
                 if r.status == ST_ERROR or r.sort_action == SORT_FAILED)
    hist = defaultdict(int)
    for r in results:
        if r.scored:
            hist[r.composite] += 1

    print()
    print(f"k2prep sort{' (dry run)' if args.report else ''}: "
          f"{len(results)} images in {_hms(elapsed)}")
    for score in range(10, 0, -1):
        if hist[score]:
            print(f"  {SORT_DIR_PREFIX}{score:<3} {hist[score]:>7}")
    verb = "moved " if args.move else "copied"
    print(f"  {verb}      {counts[SORT_COPIED] + counts[SORT_MOVED]:>7}"
          f"{'  (dry run: nothing placed)' if args.report else ''}")
    print(f"  in place    {counts[SORT_PRESENT]:>7}")
    print(f"  errors      {errors:>7}")
    if unknown:
        print(f"  unknown ext {len(unknown):>7}")
    if stale:
        print(f"  duplicates  {len(stale):>7}   (in other score folders, left alone)")
    print(f"  report      {report_path}")
    return 0


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def main(argv=None) -> int:
    args = parse_args(argv)

    folder = Path(args.folder).expanduser()
    if not folder.exists():
        print(f"error: folder does not exist: {folder}", file=sys.stderr)
        return 2
    if not folder.is_dir():
        print(f"error: not a directory: {folder}", file=sys.stderr)
        return 2
    folder = folder.resolve()

    started = datetime.now()
    t0 = time.perf_counter()

    images, unknown = scan_folder(folder)
    if not images:
        print(f"No images found in {folder} "
              f"({len(unknown)} files with unknown extensions).")

    prep_dir = folder / PREP_DIRNAME
    reports_dir = prep_dir / REPORTS_DIRNAME
    ext = ".png" if args.png else ".jpg"
    resample = RESAMPLE_FILTERS[args.filter]

    if args.sort:
        return run_sort(args, folder, prep_dir, reports_dir, images, unknown,
                        resample, started, t0)

    # -- phase A: geometry (and, in single-pass mode, source scores) ---------
    # Two-pass mode reads headers only here: nothing is decoded until there is
    # a bucket to render into.
    worker = analyse if args.single_pass else analyse_geometry
    results: list[Result] = []
    if images:
        with ThreadPoolExecutor(max_workers=args.threads) as pool:
            futures = [pool.submit(worker, p) for p in images]
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="analysing" if args.single_pass else "scanning ",
                            unit="img"):
                results.append(fut.result())
    # Report ordering is by filename, not completion order.
    results.sort(key=lambda r: r.name)
    for r in results:
        if r.status == ST_CANDIDATE:
            r.caption_src = caption_for(r.path)

    # -- preliminary report: the natural, unmerged assignment ----------------
    # Written before merging is decided and, in two-pass mode, before anything
    # is scored - so the bucket distribution it shows is the raw one, the
    # problem the merge pass exists to fix. Diff it against the final report to
    # see exactly what moved and what the rendered scores turned out to be.
    reports_dir.mkdir(parents=True, exist_ok=True)
    kind = "scan" if args.report else "process"
    stamp = f"{started:%Y%m%d-%H%M%S}"
    candidates = [r for r in results if r.status == ST_CANDIDATE]
    resolve_names(candidates, ext)
    prelim_path = _free_path(reports_dir, f"{kind}-{stamp}-preliminary", ".txt")
    prelim_path.write_text(
        build_report(args, folder, results, unknown, [], started, datetime.now(),
                     time.perf_counter() - t0, [], STAGE_PRELIMINARY),
        encoding="utf-8",
    )

    # -- phase S: render every candidate and score the result -----------------
    # The whole point of the default mode. Nothing is saved here; the rendered
    # image exists only long enough to be measured, so images that fail the
    # threshold are never written to disk at all.
    cache_hits = 0
    if not args.single_pass and candidates:
        cache = {} if args.force else load_score_cache(prep_dir)
        todo = []
        for r in candidates:
            if apply_cached_score(r, cache):
                cache_hits += 1
            else:
                todo.append(r)
        if todo:
            with ThreadPoolExecutor(max_workers=args.threads) as pool:
                futures = {pool.submit(score_rendered, r, resample): r for r in todo}
                for fut in tqdm(as_completed(futures), total=len(futures),
                                desc="scoring  ", unit="img"):
                    r = futures[fut]
                    try:
                        fut.result()
                    except Exception as exc:
                        r.status = ST_ERROR
                        r.error = f"{type(exc).__name__}: {exc}"

    # -- threshold, on whichever score was taken -----------------------------
    for r in results:
        if r.status == ST_CANDIDATE:
            r.status = ST_BELOW if r.composite < args.threshold else ST_ACCEPTED
    accepted = [r for r in results if r.status == ST_ACCEPTED]

    # -- merge: consolidate undersized buckets before writing anything -------
    moves: list[Move] = []
    unmerged: list[tuple[Result, str]] = []
    if not args.no_merge and accepted:
        moves, unmerged, _before, _after = plan_merge(accepted)

    # Names are resolved after merging, because collisions are per tier folder
    # and merging can move an image into a different tier.
    for r in results:
        r.out_stem = ""
        r.out_name = ""
        r.collided = False
        r.caption_borrowed = False
    collisions = resolve_names(accepted, ext)

    planned: dict[int, set[str]] = defaultdict(set)
    for r in accepted:
        planned[r.tier].add(r.out_name)
        if r.caption_src is not None:
            planned[r.tier].add(f"{r.out_stem}.txt")

    if not args.force:
        for r in accepted:
            if already_correct(prep_dir / str(r.tier) / r.out_name, r.bucket):
                r.status = ST_ALREADY

    removed = sweep_superseded(prep_dir, planned, dry_run=args.report)
    to_write = [r for r in results if r.status == ST_ACCEPTED]

    # -- phase C: parallel write ---------------------------------------------
    if not args.report and to_write:
        for tier in sorted({r.tier for r in to_write}):
            (prep_dir / str(tier)).mkdir(parents=True, exist_ok=True)
        with ThreadPoolExecutor(max_workers=args.threads) as pool:
            futures = {
                pool.submit(write_output, r, prep_dir / str(r.tier), resample, ext): r
                for r in to_write
            }
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="writing  ", unit="img"):
                r = futures[fut]
                try:
                    fut.result()
                except Exception as exc:
                    r.status = ST_ERROR
                    r.error = f"{type(exc).__name__}: {exc}"

    elapsed = time.perf_counter() - t0
    finished = datetime.now()

    notes: list[str] = []
    if not args.single_pass and candidates:
        # Written in dry runs too: it costs nothing and makes the recommended
        # "--report first, then run for real" workflow skip a second rendering
        # pass over the whole folder.
        save_score_cache(prep_dir, results, finished)
        notes.append(f"rendered scores cached in {CACHE_FILENAME} "
                     f"({cache_hits} of {len(candidates)} reused this run). "
                     "Delete it to force a rescore.")

    # -- toml, written every run ---------------------------------------------
    toml_path = None
    if args.report:
        notes.append(f"{TOML_FILENAME} not written: a dry run creates no tier "
                     "folders for it to point at.")
    else:
        toml_path = emit_toml(prep_dir, finished)
        if toml_path is None:
            notes.append(f"{TOML_FILENAME} not written, no tier folder has images.")
        elif toml_path.name != TOML_FILENAME:
            notes.append(f"{TOML_FILENAME} exists and was not written by k2prep, "
                         f"so it was left alone and {toml_path.name} written instead.")
    for note in notes:
        print(f"note: {note}")

    # -- final report ---------------------------------------------------------
    report_path = _free_path(reports_dir, f"{kind}-{stamp}-final", ".txt")
    report_path.write_text(
        build_report(args, folder, results, unknown, collisions,
                     started, finished, elapsed, notes, STAGE_FINAL,
                     moves, unmerged, removed),
        encoding="utf-8",
    )

    # -- console summary ------------------------------------------------------
    counts = defaultdict(int)
    for r in results:
        counts[r.status] += 1
    by_tier = defaultdict(int)
    for r in results:
        if r.status in (ST_ACCEPTED, ST_ALREADY):
            by_tier[r.tier] += 1
    undersized = sum(1 for n in bucket_counts(
        [r for r in results if r.status in (ST_ACCEPTED, ST_ALREADY)]).values()
        if 0 < n < MIN_BUCKET_SIZE)

    print()
    print(f"k2prep {'scan' if args.report else 'run'}: {len(results)} images "
          f"in {_hms(elapsed)}")
    for tier in TIERS:
        if by_tier[tier]:
            print(f"  tier {tier:<5} {by_tier[tier]:>7}")
    print(f"  written     {counts[ST_ACCEPTED]:>7}"
          f"{'  (dry run: nothing written)' if args.report else ''}")
    print(f"  already     {counts[ST_ALREADY]:>7}")
    print(f"  below thr.  {counts[ST_BELOW]:>7}")
    print(f"  too small   {counts[ST_SMALL]:>7}")
    print(f"  errors      {counts[ST_ERROR]:>7}")
    if unknown:
        print(f"  unknown ext {len(unknown):>7}")
    if not args.no_merge:
        print(f"  merged      {len(moves):>7}   "
              f"({undersized} bucket(s) still under {MIN_BUCKET_SIZE})")
    if removed:
        print(f"  superseded  {len(removed):>7}"
              f"{'  (dry run: nothing removed)' if args.report else '  removed'}")
    print(f"  reports     {prelim_path.name}")
    print(f"              {report_path.name}")
    print(f"              in {reports_dir}")
    if toml_path is not None:
        print(f"  toml        {toml_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
