# used non-standard tables (common with Adobe and several phone encoders). An
# exact IJG-scaled table fits at 0.0; Google's and Adobe's custom tables land
# well above this.
QT_RESIDUAL_MAX = 0.02

# B and D are computed on at most this square of centre pixels, for speed.
