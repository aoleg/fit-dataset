def _threshold_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threshold must be an integer, got {value!r}")
    if not 0 <= n <= 10:
        raise argparse.ArgumentTypeError(f"--threshold must be 0..10, got {n}")
    return n


def _threads_arg(value: str) -> int:
    try:
        n = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"--threads must be an integer, got {value!r}")
    if not 1 <= n <= 32:
        raise argparse.ArgumentTypeError(f"--threads must be 1..32, got {n}")
    return n


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        prog="k2prep",
        description="Crop and resize a folder of photographs onto musubi-tuner's "
                    "exact bucket dimensions for Krea 2 LoRA training.",
    )
    p.add_argument("folder", help="Input folder. Non-recursive. Never modified.")
    p.add_argument("--report", action="store_true",
                   help="Dry run: analyse and write a report, write no images.")
    p.add_argument("--threshold", type=_threshold_arg, default=0, metavar="N",
                   help="Process only images whose composite score >= N (0..10). "
                        "Default 0.")
    p.add_argument("--png", action="store_true",
                   help="Write PNG instead of JPEG q97 4:4:4.")
    p.add_argument("--filter", choices=sorted(RESAMPLE_FILTERS), default="lanczos",
                   help="Resampling filter. Default lanczos.")
    p.add_argument("--threads", type=_threads_arg, default=4, metavar="N",
                   help="Worker threads, 1..32. Default 4.")
    p.add_argument("--force", action="store_true",
                   help="Overwrite existing outputs instead of skipping.")
    p.add_argument("--emit-toml", action="store_true", dest="emit_toml",
                   help="Also write a ready-to-use musubi dataset TOML.")
    p.add_argument("--version", action="version", version=f"k2prep {__version__}")
    return p.parse_args(argv)


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------

def main(argv=None) -> int:
    args = parse_args(argv)

    folder = Path(args.folder).expanduser()
    if not folder.exists():
        print(f"error: folder does not exist: {folder}", file=sys.stderr)
        return 2
    if not folder.is_dir():
        print(f"error: not a directory: {folder}", file=sys.stderr)
        return 2
    folder = folder.resolve()

    started = datetime.now()
    t0 = time.perf_counter()

    images, unknown = scan_folder(folder)
    if not images:
        print(f"No images found in {folder} "
              f"({len(unknown)} files with unknown extensions).")

    prep_dir = folder / PREP_DIRNAME
    reports_dir = prep_dir / REPORTS_DIRNAME
    ext = ".png" if args.png else ".jpg"
    resample = RESAMPLE_FILTERS[args.filter]

    # -- phase A: parallel analysis -----------------------------------------
    results: list[Result] = []
    if images:
        with ThreadPoolExecutor(max_workers=args.threads) as pool:
            futures = [pool.submit(analyse, p) for p in images]
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="analysing", unit="img"):
                results.append(fut.result())
    # Report ordering is by filename, not completion order.
    results.sort(key=lambda r: r.name)

    # -- phase B: main thread, sequential and deterministic ------------------
    for r in results:
        if r.status == ST_CANDIDATE:
            r.caption_src = caption_for(r.path)
            if r.composite < args.threshold:
                r.status = ST_BELOW
            else:
                r.status = ST_ACCEPTED

    accepted = [r for r in results if r.status == ST_ACCEPTED]
    collisions = resolve_names(accepted, ext)

    if not args.force:
        for r in accepted:
            if (prep_dir / str(r.tier) / r.out_name).exists():
                r.status = ST_ALREADY

    to_write = [r for r in results if r.status == ST_ACCEPTED]

    # -- phase C: parallel write ---------------------------------------------
    if not args.report and to_write:
        for tier in sorted({r.tier for r in to_write}):
            (prep_dir / str(tier)).mkdir(parents=True, exist_ok=True)
        with ThreadPoolExecutor(max_workers=args.threads) as pool:
            futures = {
                pool.submit(write_output, r, prep_dir / str(r.tier), resample, args.png): r
                for r in to_write
            }
            for fut in tqdm(as_completed(futures), total=len(futures),
                            desc="writing  ", unit="img"):
                r = futures[fut]
                try:
                    fut.result()
                except Exception as exc:
                    r.status = ST_ERROR
                    r.error = f"{type(exc).__name__}: {exc}"

    elapsed = time.perf_counter() - t0
    finished = datetime.now()

    # -- toml -----------------------------------------------------------------
    notes: list[str] = []
    toml_path = None
    if args.emit_toml:
        if args.report:
            notes.append("--emit-toml ignored in --report mode "
                         "(a dry run creates no tier folders).")
        else:
            toml_path = emit_toml(prep_dir, finished)
            if toml_path is None:
                notes.append("--emit-toml wrote nothing, no tier folder has images.")
            elif toml_path.name != "dataset.toml":
                notes.append(f"dataset.toml already exists, wrote {toml_path.name} "
                             "instead; the existing file was not touched.")
    for note in notes:
        print(f"note: {note}")

    # -- report ---------------------------------------------------------------
    reports_dir.mkdir(parents=True, exist_ok=True)
    kind = "scan" if args.report else "process"
    report_path = reports_dir / f"{kind}-{started:%Y%m%d-%H%M%S}.txt"
    n = 1
    while report_path.exists():                  # never overwrite a report
        n += 1
        report_path = reports_dir / f"{kind}-{started:%Y%m%d-%H%M%S}-{n}.txt"
    report_path.write_text(
        build_report(args, folder, results, unknown, collisions,
                     started, finished, elapsed, notes),
        encoding="utf-8",
    )

    # -- console summary ------------------------------------------------------
    counts = defaultdict(int)
    for r in results:
        counts[r.status] += 1
    by_tier = defaultdict(int)
    for r in results:
        if r.status in (ST_ACCEPTED, ST_ALREADY):
            by_tier[r.tier] += 1

    print()
    print(f"k2prep {'scan' if args.report else 'run'}: {len(results)} images "
          f"in {_hms(elapsed)}")
    for tier in TIERS:
        if by_tier[tier]:
            print(f"  tier {tier:<5} {by_tier[tier]:>7}")
    print(f"  written     {counts[ST_ACCEPTED]:>7}"
          f"{'  (dry run: nothing written)' if args.report else ''}")
    print(f"  already     {counts[ST_ALREADY]:>7}")
    print(f"  below thr.  {counts[ST_BELOW]:>7}")
    print(f"  too small   {counts[ST_SMALL]:>7}")
    print(f"  errors      {counts[ST_ERROR]:>7}")
    if unknown:
        print(f"  unknown ext {len(unknown):>7}")
    print(f"  report      {report_path}")
    if toml_path is not None:
        print(f"  toml        {toml_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
