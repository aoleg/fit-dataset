    w("              rescaled after JPEG encoding; such scores are marked with ?")
    w(f"              B and D are computed on a centre crop of at most "
      f"{METRIC_CROP}x{METRIC_CROP}.")
    for note in notes:
        w(f"note        : {note}")
    w("")

    # -- target buckets ------------------------------------------------------
    w("TARGET BUCKETS")
    w("-" * 66)
    w(f"{'family':<9} {'1024 tier':<16} {'768 tier':<16} {'512 tier':<16}")
    for fam in AR_FAMILIES:
        cells = []
        for tier in TIERS:
            bw, bh = bucket_for(tier, fam)
            cells.append(f"{bw}x{bh}")
        w(f"{fam:<9} {cells[0]:<16} {cells[1]:<16} {cells[2]:<16}")
    w("")

    # -- processed -----------------------------------------------------------
    w(f"PROCESSED  ({_fmt_int(len(processed))} images)")
    w("-" * 66)
    w(f"{'filename':<{name_w}}{'source':<12}{'AR':<7}{'family':<8}{'tier':<6}"
      f"{'bucket':<12}{'crop%':>6}  {'R':<6}{'Q':>3} {'B':>3} {'D':>3} {'score':>6}")
    for r in processed:
        src = f"{r.src_w}x{r.src_h}"
        bucket = f"{r.bucket[0]}x{r.bucket[1]}"
        w(f"{r.name:<{name_w}}{src:<12}{r.src_ar:<7.3f}{r.family:<8}{r.tier:<6}"
          f"{bucket:<12}{r.crop_pct:>5.1f}%  {r.r_factor:<6.2f}"
          f"{_score_cell(r.q):>3} {_score_cell(r.b, r.b_unreliable):>3} "
          f"{_score_cell(r.d):>3} {r.composite:>6}")
    w("")

    # -- below threshold -----------------------------------------------------
    w(f"SKIPPED - below threshold {args.threshold}  ({_fmt_int(len(below))} images)")
    w("-" * 66)
    if below:
        w(f"{'filename':<{name_w}}{'source':<12}{'score':>6}  failed")
        for r in below:
            src = f"{r.src_w}x{r.src_h}"
            w(f"{r.name:<{name_w}}{src:<12}{r.composite:>6}  {_failed_metrics(r)}")
    w("")

    # -- too small -----------------------------------------------------------
    w(f"SKIPPED - too small  ({_fmt_int(len(small))} images)")
    w("-" * 66)
    if small:
        w(f"{'filename':<{name_w}}{'source':<12}{'family':<8}{'post-crop':<13}{'needed':>10}")
        for r in small:
            src = f"{r.src_w}x{r.src_h}"
            post = f"{r.crop[0]}x{r.crop[1]}" if r.crop else "-"
            w(f"{r.name:<{name_w}}{src:<12}{r.family or '-':<8}{post:<13}"
              f"{_fmt_int(r.need):>10}")
    w("")

    # -- already processed ---------------------------------------------------
    w(f"SKIPPED - already processed  ({_fmt_int(len(already))} images)")
    w("-" * 66)
    for r in already:
        w(f"{r.name:<{name_w}}-> {r.tier}/{r.out_name}")
    w("")

    # -- collisions ----------------------------------------------------------
    w(f"FILENAME COLLISIONS  ({len(collisions)})")
    w("-" * 66)
    for line in collisions:
        w(line)
    w("")

    # -- missing captions ----------------------------------------------------
    missing = [r.name for r in processed if r.caption_src is None]
    w(f"MISSING CAPTIONS  ({_fmt_int(len(missing))})")
    w("-" * 66)
    for n in missing:
        w(n)
    w("")

    # -- unknown extension ---------------------------------------------------
    w(f"SKIPPED - unknown extension  ({_fmt_int(len(unknown))})")
    w("-" * 66)
    for n in unknown:
        w(n)
    w("")

    # -- errors --------------------------------------------------------------
    w(f"ERRORS  ({_fmt_int(len(errors))})")
    w("-" * 66)
    for r in errors:
        w(f"{r.name:<{name_w}}{r.error}")
    w("")

    no_metrics = [r for r in tiered if r.no_metrics]
    if no_metrics:
        w(f"NO USABLE METRICS - scored 10 by default  ({len(no_metrics)})")
        w("-" * 66)
        for r in no_metrics:
            w(r.name)
        w("")

    # -- summary -------------------------------------------------------------
    w("=" * 66)
    w("SUMMARY")
    w("=" * 66)
    w("")

    total = len(results)
    w("TIER DISTRIBUTION")
    by_tier = defaultdict(int)
    for r in processed:
        by_tier[r.tier] += 1
    def dist_row(label: str, n: int, note: str = "", pct: bool = True) -> None:
        line = f"  {label:<8}{_fmt_int(n):>7}"
        if pct:
            line += f"   {100.0 * n / max(total, 1):>5.1f}%"
        if note:
            line += f"   {note}"
        w(line)

    for tier in TIERS:
        dist_row(f"{tier:>4}", by_tier[tier])
    dist_row("skipped", len(below) + len(small),
             f"({len(below)} below threshold, {len(small)} too small)")
    if already:
        dist_row("already", len(already), "(counted in the tiers above)")
    if errors:
        dist_row("errors", len(errors))
    dist_row("total", total, pct=False)
    w("")

    w("BUCKET DISTRIBUTION")
    for tier in TIERS:
        rows = [r for r in processed if r.tier == tier]
        if not rows:
            continue
        w(f"  tier {tier}")
        counts = defaultdict(int)
        fam_of = {}
        for r in rows:
            counts[r.bucket] += 1
            fam_of[r.bucket] = r.family
        for bucket, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
            label = f"{bucket[0]}x{bucket[1]}"
            warns = []
            if n < 8:
                warns.append("fewer than 8 images")
            if n % 2 == 1:
                warns.append("odd count, trailing batch of 1")
            note = f"   *** WARNING: {'; '.join(warns)}" if warns else ""
            w(f"    {label:>11} {fam_of[bucket]:<6} {_fmt_int(n):>8}{note}")
    if not processed:
        w("  (none)")
    w("")

    w("QUALITY DISTRIBUTION (composite, all images that fit a tier)")
    hist = defaultdict(int)
    for r in tiered:
        hist[r.composite] += 1
    peak = max(hist.values()) if hist else 0
    for score in range(10, 0, -1):
        n = hist[score]
        bar = "#" * (round(40 * n / peak) if peak else 0)
        pct = 100.0 * n / max(len(tiered), 1)
        w(f"  {score:>2}  {bar:<40}  {_fmt_int(n):>8}  {pct:>5.1f}%")
    w("")

    w("CROP COST")
    crops = [r.crop_pct for r in processed]
    if crops:
        w(f"  {'median crop':<17}{statistics.median(crops):>5.1f}%")
        w(f"  {'mean crop':<17}{statistics.fmean(crops):>5.1f}%")
        w(f"  {'images >25% crop':<17}{len([c for c in crops if c > 25.0]):>5}")
        heavy = sorted(processed, key=lambda r: (-r.crop_pct, r.name))[:20]
        w("  heaviest 20:")
        for r in heavy:
            w(f"    {r.name:<{name_w}}{r.crop_pct:>5.1f}%   "
              f"({r.src_w}x{r.src_h} -> {r.family})")
    else:
        w("  (no images processed)")
    w("")

    w("TIMING")
    rate = total / elapsed if elapsed > 0 else 0.0
    w(f"  scanned  {_fmt_int(total)} images in {_hms(elapsed)} "
      f"({rate:.1f} img/s, {args.threads} threads)")

    return "\n".join(line.rstrip() for line in out) + "\n"


